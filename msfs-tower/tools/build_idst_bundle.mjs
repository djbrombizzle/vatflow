// Bundles tools/idst-entry.js (the VATFLOW release engine from shared/) into one
// plain script for the in-cab IDST gauge. Run from anywhere:
//   node msfs-tower/tools/build_idst_bundle.mjs
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "package", "html_ui", "Pages", "VCockpit", "Instruments",
  "VatflowTower", "common", "vatflow-metering.js");
execFileSync("npx", ["--yes", "esbuild@0.24.0", join(here, "idst-entry.js"),
  "--bundle", "--format=iife", "--global-name=VatflowMetering", "--target=es2017", "--legal-comments=none",
  "--banner:js=/* GENERATED by msfs-tower/tools/build_idst_bundle.mjs from shared/fca-metering.js - do not edit */",
  "--outfile=" + out], { stdio: "inherit" });
console.log("wrote", out);
