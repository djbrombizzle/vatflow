// Builds the in-cab screens' copies of VATFLOW code from shared/ (MSFS gauges load plain
// scripts, not ES modules), and the KDCA ramp layout they need. Run from anywhere:
//   node msfs-tower/tools/build_vatflow_bundles.mjs
//
//   common/vatflow-metering.js  VatflowMetering  IDST release engine (shared/fca-metering.js ...)
//   common/vatflow-ramp.js      VatflowRamp      ramp list logic (shared/ramp-core.js)
//   common/vatflow-smart.js     VatflowSmart     VATSMART analysis (shared/vatsmart.js and friends)
//   common/ramp-kdca.js         VATFLOW_RAMP_LAYOUT  data/ramp/KDCA.json, trimmed to what the list uses
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const common = join(here, "..", "package", "html_ui", "Pages", "VCockpit", "Instruments", "VatflowTower", "common");

function bundle(entry, globalName, outFile, source) {
  execFileSync("npx", ["--yes", "esbuild@0.24.0", join(here, entry),
    "--bundle", "--format=iife", "--global-name=" + globalName, "--target=es2017", "--legal-comments=none",
    `--banner:js=/* GENERATED by msfs-tower/tools/build_vatflow_bundles.mjs from ${source} - do not edit */`,
    "--outfile=" + join(common, outFile)], { stdio: "inherit" });
}

bundle("idst-entry.js", "VatflowMetering", "vatflow-metering.js", "shared/fca-metering.js");
bundle("ramp-entry.js", "VatflowRamp", "vatflow-ramp.js", "shared/ramp-core.js");
bundle("vatsmart-entry.js", "VatflowSmart", "vatflow-smart.js", "shared/vatsmart.js");

const raw = JSON.parse(readFileSync(join(repo, "data", "ramp", "KDCA.json"), "utf8"));
// the list needs the stands / ramps / airlines; the map also the views, buildings and spots
const keep = ["icao", "name", "field", "charts", "views", "lanes", "stands", "ramps", "buildings", "callSpots",
  "deiceSpots", "aprons", "operators", "airlines"];
const layout = {};
for (const k of keep) if (raw[k] !== undefined) layout[k] = raw[k];
writeFileSync(join(common, "ramp-kdca.js"),
  "/* GENERATED by msfs-tower/tools/build_vatflow_bundles.mjs from data/ramp/KDCA.json - do not edit */\n" +
  "var VATFLOW_RAMP_LAYOUT = " + JSON.stringify(layout) + ";\n");
console.log("wrote bundles and ramp-kdca.js to", common);
