"""
Builds common/faa-towers.js: every airport control tower in the FAA's Digital Obstacle
File (obstacle type CTRL TWR), with its position and height, for placing the cab.

  python tools/build_faa_towers.py [DOF.DAT or DAILY_DOF_DAT.ZIP]

Without a file it downloads https://aeronav.faa.gov/Obst_Data/DAILY_DOF_DAT.ZIP (~15 MB).
Only towers whose horizontal accuracy is +-250 ft or better are kept (codes 1-4; most
are code 1, +-20 ft). Each entry: [lat, lon, height above ground ft, top ft MSL].
At runtime common/placement.js takes the tallest tower within 2.5 nm of the airport
(an airport's old tower is usually the shorter one).
"""

import io
import json
import os
import sys
import urllib.request
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "package", "html_ui", "Pages", "VCockpit", "Instruments", "VatflowTower", "common", "faa-towers.js")
URL = "https://aeronav.faa.gov/Obst_Data/DAILY_DOF_DAT.ZIP"


def lines(src):
    if src and src.lower().endswith(".dat"):
        return open(src, encoding="latin-1").read().splitlines()
    data = open(src, "rb").read() if src else urllib.request.urlopen(URL, timeout=300).read()
    z = zipfile.ZipFile(io.BytesIO(data))
    name = next(n for n in z.namelist() if n.upper().endswith(".DAT"))
    return z.read(name).decode("latin-1").splitlines()


def main(src=None):
    rows, currency = [], ""
    for l in lines(src):
        if "CURRENCY DATE" in l:
            currency = l.split("=")[-1].strip()
        if l[62:80].strip() != "CTRL TWR" or l[97] not in "1234":
            continue
        lat = int(l[35:37]) + int(l[38:40]) / 60 + float(l[41:46]) / 3600
        lon = int(l[48:51]) + int(l[52:54]) / 60 + float(l[55:60]) / 3600
        lat *= 1 if l[46] == "N" else -1
        lon *= -1 if l[60] == "W" else 1
        rows.append([round(lat, 6), round(lon, 6), int(l[83:88]), int(l[89:94])])
    with open(OUT, "w", newline="\n") as f:
        f.write("/* GENERATED by msfs-tower/tools/build_faa_towers.py from the FAA Digital Obstacle File "
                "(CTRL TWR, currency %s) - do not edit */\n" % currency)
        f.write("/* [lat, lon, height above ground ft, top ft MSL] */\n")
        f.write("var VATFLOW_FAA_TOWERS = %s;\n" % json.dumps(rows, separators=(",", ":")))
    print("wrote %s: %d towers (DOF %s)" % (OUT, len(rows), currency))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
