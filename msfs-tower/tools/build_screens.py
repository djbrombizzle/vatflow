"""
Writes the screen host pages: Screen/S_<id>.html + .js for every 1024x768 cab screen, and the
matching part of Screen/Screen.css. Each page loads every app (Screen/Screen.js shows one at a
time, picked with the screen's MENU tab). Run after adding an app or a screen:

  python tools/build_screens.py

faceDeg: which window the screen looks out of, degrees left of the front window (map apps
turn so their top is that view). mount: an overhead monitor on the ceiling track (its
track position and swivel are added).
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
INST = os.path.join(HERE, "..", "package", "html_ui", "Pages", "VCockpit", "Instruments", "VatflowTower")
BASE = "/Pages/VCockpit/Instruments/VatflowTower/"

#        id            dim group  mount     faceDeg  default     where it isn't available
SCREENS = [
    ("DBRITE",      "DBRITE",  "DBRITE",  -45,  "dbrite",    "setup"),
    ("ASDEX",       "ASDEX",   "ASDEX",    45,  "asdex",     "setup"),
    ("IDST",        "CONSOLE", None,       45,  "idst",      "setup"),
    ("APTDEMAND",   "CONSOLE", None,      135,  "aptdemand", "setup"),
    ("APTLIST",     "CONSOLE", None,      135,  "aptlist",   "setup"),
    ("RAMP",        "CONSOLE", None,       90,  "ramp",      "setup"),
    ("VATSMART",    "CONSOLE", None,      135,  "vatsmart",  "setup"),
    ("RAMPMAP_ED",  "CONSOLE", None,       90,  "rampED",    "aptlist"),
    ("RAMPMAP_CB",  "CONSOLE", None,        0,  "rampCB",    "asdex"),
    ("RAMPMAP_AS",  "CONSOLE", None,        0,  "rampAS",    "dbrite"),
]

CSS = ["Screen/Screen.css", "Setup/Setup.css", "StripSetup/StripSetup.css", "Dbrite/Dbrite.css", "Asdex/Asdex.css", "Idst/Idst.css",
       "Vatsmart/Vatsmart.css", "AptDash/AptDash.css", "Ramp/Ramp.css", "RampMap/RampMap.css"]

SCRIPTS = [
    "common/compat.js", "common/store.js", "common/airport.js",
    "common/airports/KDCA.js", "common/airports/KATL.js", "common/towers.js",
    "common/vatsim-feed.js", "common/draw.js", "common/dimmer.js",
    "common/osm-airport.js", "common/site.js", "common/placement.js", "common/vnas.js", "common/mappicker.js", "common/strips.js",
    "common/vatflow-hub.js", "common/vatflow-metering.js", "common/vatflow-smart.js", "common/apt-flow.js",
    "common/vatflow-ramp.js", "common/ramp-kdca.js", "common/ramp-data.js",
    "Dbrite/Dbrite.js", "Asdex/Asdex.js", "Idst/Idst.js", "Vatsmart/Vatsmart.js", "AptDash/AptDash.js",
    "Ramp/Ramp.js", "RampMap/RampMap.js", "Setup/Setup.js", "StripSetup/StripSetup.js", "Screen/Screen.js",
]


def main():
    out_dir = os.path.join(INST, "Screen")
    for sid, group, mount, face, dflt, alt in SCREENS:
        tmpl = "VatflowScreen" + sid
        lines = ['<!-- Generated by msfs-tower/tools/build_screens.py - do not edit. -->']
        lines += ['<link rel="stylesheet" href="%s%s" />' % (BASE, c) for c in CSS]
        lines += ['<script type="text/html" id="%s">' % tmpl, '  <div class="scr-root"></div>', "</script>"]
        lines += ['<script type="text/html" import-script="%s%s"></script>' % (BASE, s) for s in SCRIPTS + ["Screen/S_%s.js" % sid]]
        with open(os.path.join(out_dir, "S_%s.html" % sid), "w", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        desc = '{ id: "%s", group: "%s", %sfaceDeg: %d, def: "%s", alt: "%s" }' % (
            sid, group, ('mount: "%s", ' % mount) if mount else "", face, dflt, alt)
        with open(os.path.join(out_dir, "S_%s.js" % sid), "w", newline="\n") as f:
            f.write("/* Generated by msfs-tower/tools/build_screens.py - do not edit. */\n")
            f.write("vatflowRegisterScreen(%s);\n" % desc)
    # strip bays and their position signs (StripBay/StripBay.js)
    strip_scripts = ["common/store.js", "common/airport.js", "common/airports/KDCA.js", "common/airports/KATL.js",
                     "common/vatsim-feed.js", "common/draw.js", "common/dimmer.js", "common/site.js", "common/strips.js",
                     "StripBay/StripBay.js"]
    sdir = os.path.join(INST, "StripBay")
    for n in range(1, 4):
        for sign, (pre, w, h) in ((False, ("SB", 512, 896)), (True, ("SG", 512, 128))):
            tmpl = ("VatflowSign%d" if sign else "VatflowStrips%d") % n
            lines = ['<!-- Generated by msfs-tower/tools/build_screens.py - do not edit. -->',
                     '<link rel="stylesheet" href="%sStripBay/StripBay.css" />' % BASE,
                     '<script type="text/html" id="%s">' % tmpl,
                     '  <canvas width="%d" height="%d"></canvas>' % (w, h), "</script>"]
            lines += ['<script type="text/html" import-script="%s%s"></script>' % (BASE, x)
                      for x in strip_scripts + ["StripBay/%s_%d.js" % (pre, n)]]
            with open(os.path.join(sdir, "%s_%d.html" % (pre, n)), "w", newline="\n") as f:
                f.write("\n".join(lines) + "\n")
            with open(os.path.join(sdir, "%s_%d.js" % (pre, n)), "w", newline="\n") as f:
                f.write("/* Generated by msfs-tower/tools/build_screens.py - do not edit. */\n")
                f.write("vatflowRegisterStripBay(%d, %s);\n" % (n, "true" if sign else "false"))
    tags = ", ".join("vatflow-screen-%s" % s[0].lower() for s in SCREENS)
    with open(os.path.join(out_dir, "Screen.css"), "w", newline="\n") as f:
        f.write("/* Screen host (Screen/Screen.js): one app at a time filling the 1024x768 screen. */\n")
        f.write("%s { display: block; width: 100%%; height: 100%%; }\n" % tags)
        f.write(".scr-root { display: block; width: 100%; height: 100%; }\n")
        f.write("vatflow-setup { display: block; width: 100%; height: 100%; }\n")
    print("wrote %d screens" % len(SCREENS))


if __name__ == "__main__":
    main()
