#!/usr/bin/env node
/**
 * Build shared/zdc-reference-data.js from data/zdc-reference/*.json (one file
 * per vZDC SOP / LOA / procedure, see data/zdc-reference/README.md).
 * Validates every item and fails on anything the page could mis-match.
 * Usage: node scripts/build-zdc-reference.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "data", "zdc-reference");
const OUT = join(ROOT, "shared", "zdc-reference-data.js");

const CATS = [
  "Departure", "Arrival", "Overflight", "Handoff", "Airspace", "Runway config", "Ground",
  "Clearance", "Coordination", "Frequencies", "SFRA", "Special use", "General",
];
const ACFT = ["", "jet", "prop", "tp", "pn", "heli"];
const KIND_ORDER = { SOP: 0, PROC: 1, LOA: 2 };

const errors = [];
const fail = (where, msg) => errors.push(`${where}: ${msg}`);
const up = a => (Array.isArray(a) ? a : []).map(s => String(s).trim().toUpperCase()).filter(Boolean);

const docs = [], items = [];
for (const name of readdirSync(SRC).filter(f => f.endsWith(".json")).sort()) {
  const j = JSON.parse(readFileSync(join(SRC, name), "utf8"));
  const d = j.doc;
  if (!d || !d.id || !d.title) { fail(name, "missing doc.id/title"); continue; }
  docs.push({
    id: d.id, title: d.title, kind: d.kind || "LOA", number: d.number || "", parties: d.parties || [],
    effective: d.effective || "", summary: d.summary || "",
  });
  j.items.forEach((it, i) => {
    const w = `${d.id}#${i} "${it.title}"`;
    const item = {
      doc: d.id, ref: String(it.ref || ""), cat: it.cat, title: String(it.title || "").trim(),
      text: String(it.text || "").trim(), restr: String(it.restr || "").trim(),
      from: String(it.from || ""), to: String(it.to || ""),
      dep: up(it.dep), arr: up(it.arr), fixes: up(it.fixes),
      fixMode: it.fixMode === "all" ? "all" : "any", acft: String(it.acft || "").toLowerCase(),
      minAlt: it.minAlt ?? null, maxAlt: it.maxAlt ?? null, flow: String(it.flow || ""),
      both: !!it.both, fr: String(it.fr || "").toUpperCase(), live: !!it.live, kw: Array.isArray(it.kw) ? it.kw.map(String) : [],
    };
    if (!CATS.includes(item.cat)) fail(w, `bad cat ${item.cat}`);
    if (!item.title || !item.text) fail(w, "missing title/text");
    if (!["", "IFR", "VFR"].includes(item.fr)) fail(w, `bad fr ${item.fr}`);
    if (item.both && (!item.dep.length || !item.arr.length)) fail(w, "both needs dep and arr");
    if (!ACFT.includes(item.acft)) fail(w, `bad acft ${item.acft}`);
    for (const a of [...item.dep, ...item.arr]) if (!/^[A-Z][A-Z0-9]{3}$/.test(a)) fail(w, `airport not ICAO: ${a}`);
    for (const f of item.fixes) if (!/^[A-Z0-9]{2,7}$/.test(f)) fail(w, `bad fix token: ${f}`);
    for (const k of ["minAlt", "maxAlt"]) if (item[k] != null && !(Number.isFinite(item[k]) && item[k] >= 1000)) fail(w, `${k} must be feet`);
    if (item.live && !item.dep.length && !item.arr.length && !item.fixes.length) item.live = false;
    // Compact output: drop empty fields.
    for (const k of Object.keys(item)) {
      const v = item[k];
      if (v === "" || v === null || (Array.isArray(v) && !v.length) || v === false || (k === "fixMode" && v === "any")) delete item[k];
    }
    items.push(item);
  });
}

if (errors.length) {
  console.error(errors.join("\n"));
  console.error(`\n${errors.length} problem(s); nothing written.`);
  process.exit(1);
}

docs.sort((a, b) => (KIND_ORDER[a.kind] ?? 9) - (KIND_ORDER[b.kind] ?? 9) || a.title.localeCompare(b.title));
const js = `/**
 * vZDC SOP / LOA / procedure reference items for zdc-reference.html.
 * GENERATED by scripts/build-zdc-reference.mjs from data/zdc-reference/*.json — edit those, then rebuild.
 * The ZDC center SOP (vZDC-ZDC-P-01J) crossing tables live in shared/zdc-sop-data.js.
 */
export const REF_DOCS = ${JSON.stringify(docs, null, 1)};

export const REF_ITEMS = [
${items.map(i => JSON.stringify(i)).join(",\n")}
];
`;
writeFileSync(OUT, js);
console.log(`${docs.length} documents, ${items.length} items (${items.filter(i => i.live).length} live) → shared/zdc-reference-data.js`);
